/// UI text in the child's own language. Placeholders are `{name}`.
///
/// Kept as plain maps: five languages, about seventy lines each, no codegen.
/// `test/l10n/strings_test.dart` checks every language has every key and the
/// same placeholders.
class Strings {
  const Strings(this.lang);

  final String lang;

  String t(String key, [Map<String, Object> args = const {}]) {
    var text = strings[lang]?[key] ?? strings['en']![key] ?? key;
    args.forEach((k, v) => text = text.replaceAll('{$k}', '$v'));
    return text;
  }

  /// Digit words for the parent gate, 0 to 9.
  List<String> get digits => t('digits').split(',');
}

